let state = {
  loaded: false,
  loading: null,
  error: null,
  words: [],
  bySimplified: new Map(),
  byTraditional: new Map(),
  byId: new Map(),
  chars: {},
  charIndex: new Map(),
  simpToTrad: new Map(),
  tradToSimp: new Map(),
  maxWordLength: 1,
  meta: null,
  charMeta: null,
};

/* ---------------------------------------------------------------- load --- */

async function fetchJson(url) {
  const response = await fetch(url, { cache: 'force-cache' });
  if (!response.ok) throw new Error(`${url} -> HTTP ${response.status}`);
  return response.json();
}

export function loadDictionary() {
  if (state.loaded) return Promise.resolve(state);
  if (state.loading) return state.loading;

  state.loading = (async () => {
    try {
      const [wordsDoc, charsDoc] = await Promise.all([fetchJson(WORDS_URL), fetchJson(CHARS_URL)]);
      // The script map only drives interface labels; a failure here must not
      // stop the app from working, so it is loaded separately and tolerated.
      let scriptDoc = null;
      try {
        scriptDoc = await fetchJson(SCRIPT_URL);
      } catch (error) {
        console.warn('[dictionary] simplified/traditional map unavailable', error);
      }
      loadFrom(wordsDoc, charsDoc, scriptDoc);
      state.loaded = true;
      state.error = null;
    } catch (error) {
      state.error = error;
      console.error('[dictionary] failed to load seed data', error);
    } finally {
      state.loading = null;
    }
    return state;
  })();

  return state.loading;
}

/** Also used by tests: inject documents directly. */
export function loadFrom(wordsDoc, charsDoc, scriptDoc) {
  const words = (wordsDoc?.words || []).map((word, index) => ({
    ...word,
    id: index + 1,
    length: word.s.length,
    syllables: word.p.split(/\s+/),
  }));

  state.words = words;
  state.bySimplified = new Map(words.map((word) => [word.s, word]));
  state.byTraditional = new Map(words.filter((word) => word.t).map((word) => [word.t, word]));
  state.byId = new Map(words.map((word) => [word.id, word]));
  state.maxWordLength = words.reduce((max, word) => Math.max(max, word.length), 1);
  state.meta = wordsDoc?.meta || null;

  const chars = charsDoc?.chars || {};
  state.chars = chars;
  state.charIndex = new Map(Object.entries(chars));
  state.charMeta = charsDoc?.meta || null;

  state.simpToTrad = new Map(Object.entries(scriptDoc?.st || {}));
  // invert once so traditional text can be normalised back for lookup
  state.tradToSimp = new Map();
  for (const [simplified, traditional] of state.simpToTrad) {
    if (!state.tradToSimp.has(traditional)) state.tradToSimp.set(traditional, simplified);
  }
  return state;
}

