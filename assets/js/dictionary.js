/* ==========================================================================
   dictionary.js — loads the static seed data and answers word queries.

   data/words.json is generated by tools/build_dictionary.py from
   phrase-pinyin-data + jieba frequencies. When the backend lands, this module
   becomes a thin fetch wrapper around /api/words and /api/lookup; the exported
   functions are already shaped that way.
   ========================================================================== */

